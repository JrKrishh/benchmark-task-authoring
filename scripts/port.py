#!/usr/bin/env python3
"""port.py — generate this skill's entry points for other agent tools.

`references/` and `SKILL.md` are the single source of truth. Every other tool wants
the same knowledge behind a different filename and frontmatter convention, so those
files are GENERATED rather than hand-maintained — four hand-edited copies drift, and
a stale rule file is worse than no rule file.

    python scripts/port.py            # regenerate all targets
    python scripts/port.py --check    # exit 1 if any target is stale (for CI)

Targets
    AGENTS.md            OpenAI Codex, Google Antigravity, and most AGENTS.md readers
    .cursor/rules/*.mdc  Cursor — native frontmatter, glob auto-attach
    .agents/rules/*.md   Antigravity workspace rules
"""
import argparse, io, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BANNER = ("<!-- GENERATED by scripts/port.py from SKILL.md + references/. "
          "Edit those, then re-run port.py. -->\n")

# Cursor/Antigravity attach rules by glob. These are real patterns, unlike the
# placeholder paths used in prose.
RULE_META = {
    "00-mission":         ("Core mission, authorship boundaries and the phase map. Always active.", None, True),
    "05-retrieval":       ("Retrieve from the local index instead of re-reading long documents.", None, True),
    "10-hardness-gate":   ("The hardness law, its pre-build check and the strong-probe protocol. Load when designing a task, judging whether a design is hard enough, or diagnosing a pass@ result that came back too easy.", None, False),
    "20-design-doctrine": ("Measured dead ends and what the accepted-task corpus looks like. Load before proposing or choosing a task shape.", None, False),
    "30-harbor-format":   ("Harbor/TB2 mechanical format: file layout, task.toml schema, Dockerfile rules, base images, timeouts, preflight. Auto-attaches to task files.", "**/task/**", False),
    "40-authoring":       ("instruction.md style rules, the 4-section proposal format, and rubric alignment. Auto-attaches to instruction and proposal files.", "**/instruction.md,**/proposal-*.md", False),
    "50-verifier":        ("Verifier design: ground-truth protection, tolerance justification, anti-cheat, and the pre-submission self-check. Auto-attaches to test files.", "**/task/tests/**", False),
    "60-pipeline":        ("Submission pipeline: fork/PR flow, the automated check stages, pass@2 and pass@5 economics, reading feedback, revision limits.", None, False),
}


def read(p):
    return io.open(os.path.join(ROOT, p), encoding="utf-8").read()


def strip_frontmatter(s):
    m = re.match(r"^---\n.*?\n---\n(.*)$", s, re.S)
    return m.group(1) if m else s


def build_agents_md():
    """One file carrying the core, for tools that read AGENTS.md."""
    body = strip_frontmatter(read("SKILL.md")).lstrip("\n")
    # Drop SKILL.md's own H1 — this file supplies its own, plus a "which file am I"
    # note, because a reader may land here without knowing the other ports exist.
    body = re.sub(r"\A#\s+.*?\n", "", body, count=1)
    head = (
        "# Authoring hard agent-benchmark tasks\n"
        "\n"
        "> **Which file am I?** The `AGENTS.md` entry point, read automatically by OpenAI Codex,\n"
        "> Google Antigravity, and other AGENTS.md-aware agents. Cursor reads the same knowledge\n"
        "> from `.cursor/rules/`; Claude Code from `SKILL.md`. All of them are generated from one\n"
        "> source — edit `SKILL.md` or `references/`, then run `python scripts/port.py`.\n"
        "\n"
        "Everything below applies whenever you are designing, building, critiquing or debugging a\n"
        "Terminal-Bench 2 / Harbor benchmark task.\n"
        "\n"
    )
    return BANNER + head + body


def build_rule_files():
    """Cursor .mdc (frontmatter + globs) and Antigravity .agents/rules/*.md."""
    out = []
    for name, (desc, globs, always) in RULE_META.items():
        src = "references/rules/%s.md" % name
        if not os.path.exists(os.path.join(ROOT, src)):
            continue
        content = strip_frontmatter(read(src))

        fm = ["---", "description: %s" % desc]
        if globs:
            fm.append("globs: %s" % globs)
        fm += ["alwaysApply: %s" % ("true" if always else "false"), "---", ""]
        out.append((".cursor/rules/%s.mdc" % name, BANNER + "\n".join(fm) + content))

        # Antigravity workspace rules: same content, plain md, description in frontmatter.
        afm = ["---", "description: %s" % desc, "---", ""]
        out.append((".agents/rules/%s.md" % name, BANNER + "\n".join(afm) + content))
    return out


def targets():
    t = [("AGENTS.md", build_agents_md())]
    t += build_rule_files()
    # A pointer so Antigravity/Cursor users find the deep material.
    t.append((".agents/rules/99-references.md", BANNER + """---
description: Where the full evidence lives. Load when a rule above cites a law, a CI stage, or a repair mechanism.
---

# The reference material

The rule files above are the working summary. The evidence, with numbers and evidence
classes, lives in these files — read the one the situation calls for rather than all of them.

| File | Load it when |
|---|---|
| `references/hardness-laws.md` | Designing or red-teaming a task shape; diagnosing a result. ~35k tokens — use its table of contents, or query it with `scripts/dr.py` |
| `references/category-*.md` | **Check first.** A brief for your category: its measured record, the shapes already killed there, and a pre-build checklist. Currently Mathematics & Formal Reasoning, and Model Training & ML Infrastructure |
| `references/ci-stages.md` | Before any push, and whenever a review stage fails. All 17 stages, the four blockers a preflight misses, the ordered local pipeline |
| `references/claiming.md` | Claiming a slot |
| `assets/proposal-template.md` | Writing the proposal — it is a graded artifact with a strict format |
| `assets/slot-session-prompt.md` | Starting work on a slot |
| `assets/batch-brief-template.md` | Holding three or more slots at once |

Tools you can run directly:

```bash
python scripts/dr.py index --no-embed        # index this material, then ask it questions
python scripts/preflight.py <task-dir>       # local gate check before pushing
python scripts/taskdesk.py --org <your-org>  # board: which stage each slot is at
```
"""))
    return t


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 if any target is stale")
    a = ap.parse_args()

    stale, wrote = [], []
    for rel, content in targets():
        path = os.path.join(ROOT, rel)
        cur = io.open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if cur == content:
            continue
        if a.check:
            stale.append(rel)
            continue
        d = os.path.dirname(path)
        if d and not os.path.isdir(d):
            os.makedirs(d)
        io.open(path, "w", encoding="utf-8", newline="").write(content)
        wrote.append(rel)

    if a.check:
        if stale:
            print("stale (run scripts/port.py): " + ", ".join(stale))
            sys.exit(1)
        print("all entry points current")
    else:
        print("regenerated %d file(s)%s" % (len(wrote), (": " + ", ".join(wrote)) if wrote else ""))


if __name__ == "__main__":
    main()
